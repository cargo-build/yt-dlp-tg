impl Language {
    pub fn from_code(code: Option<&str>) -> Self {
        Self(match code.map(|s| s.split(['-', '_']).next()) {
            Some(Some("zh")) => 1,
            Some(Some("hi")) => 2,
            Some(Some("es")) => 3,
            Some(Some("ar")) => 4,
            Some(Some("fr")) => 5,
            Some(Some("pt")) => 6,
            Some(Some("ru")) => 7,
            _ => 0,
        })
    }

    pub fn code(self) -> &'static str {
        CODES[self.0]
    }

    pub fn text(self, text: Text) -> &'static str {
        COPY[self.0][text as usize]
    }
}

